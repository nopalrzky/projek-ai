import 'package:equatable/equatable.dart';
import 'package:wash_wallet_core/wash_wallet_core.dart';
import 'package:wash_wallet_domain/wash_wallet_domain.dart';

sealed class ExpenseState extends Equatable {
  const ExpenseState();

  @override
  List<Object?> get props => [];
}

class ExpenseInitial extends ExpenseState {
  const ExpenseInitial();
}

class ExpenseLoading extends ExpenseState {
  const ExpenseLoading();
}

class ExpensesLoaded extends ExpenseState {
  final List<Expense> expenses;
  final bool hasReachedMax;
  final int currentPage;
  final int lastPage;
  final int total;
  final int? from;
  final int? to;
  final int perPage;
  final bool isPageLoading;

  const ExpensesLoaded({
    required this.expenses,
    this.hasReachedMax = false,
    this.currentPage = 1,
    this.lastPage = 1,
    this.total = 0,
    this.from,
    this.to,
    this.perPage = 15,
    this.isPageLoading = false,
  });

  ExpensesLoaded copyWith({
    List<Expense>? expenses,
    bool? hasReachedMax,
    int? currentPage,
    int? lastPage,
    int? total,
    int? from,
    int? to,
    int? perPage,
    bool? isPageLoading,
  }) {
    return ExpensesLoaded(
      expenses: expenses ?? this.expenses,
      hasReachedMax: hasReachedMax ?? this.hasReachedMax,
      currentPage: currentPage ?? this.currentPage,
      lastPage: lastPage ?? this.lastPage,
      total: total ?? this.total,
      from: from ?? this.from,
      to: to ?? this.to,
      perPage: perPage ?? this.perPage,
      isPageLoading: isPageLoading ?? this.isPageLoading,
    );
  }

  @override
  List<Object?> get props => [
        expenses,
        hasReachedMax,
        currentPage,
        lastPage,
        total,
        from,
        to,
        perPage,
        isPageLoading,
      ];
}

class ExpenseDetailLoaded extends ExpenseState {
  final Expense expense;

  const ExpenseDetailLoaded(this.expense);

  @override
  List<Object?> get props => [expense];
}

class ExpenseActionSuccess extends ExpenseState {
  final String message;
  final Expense? expense;

  const ExpenseActionSuccess(this.message, {this.expense});

  @override
  List<Object?> get props => [message, expense];
}

class ExpenseFailure extends ExpenseState {
  final Failure failure;

  const ExpenseFailure(this.failure);

  @override
  List<Object?> get props => [failure];
}
